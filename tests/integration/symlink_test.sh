#!/usr/bin/env bash
# Integration tests: repo-kickoff installed the way the README says, as a
# symlink on PATH pointing into the clone, and run from an unrelated folder.
# The generated repository must work on its own.

# shellcheck source=tests/lib.sh
. "$TESTS_DIR/lib.sh"

unset REPO_KICKOFF_TYPES

# Put a symlink to bin/repo-kickoff in $TEST_TMP/onpath, and make an
# unrelated working folder, $TEST_TMP/work.
install_on_path() {
	mkdir onpath work
	ln -s "$REPO_ROOT/bin/repo-kickoff" onpath/repo-kickoff
	PATH=$TEST_TMP/onpath:$PATH
	export PATH
}

test_symlinked_command_generates_bash_cli_from_another_folder() {
	install_on_path
	cd work || exit 1
	[ "$(command -v repo-kickoff)" = "$TEST_TMP/onpath/repo-kickoff" ] ||
		_fail "repo-kickoff is not the symlink on PATH: $(command -v repo-kickoff)"
	run repo-kickoff bash-cli greet
	assert_status 0
	assert_contains "$OUT" "Created greet from the bash-cli type."
	assert_executable "$TEST_TMP/work/greet/bin/greet"
}

test_generated_command_runs_and_its_smoke_test_passes() {
	install_on_path
	cd work || exit 1
	run repo-kickoff bash-cli greet
	assert_status 0
	run greet/bin/greet
	assert_status 0
	assert_eq "greet: placeholder - nothing implemented yet" "$OUT"
	run greet/tests/smoke.sh
	assert_status 0
	assert_eq "smoke: ok" "$OUT"
}

test_generated_repository_stands_on_its_own() {
	install_on_path
	cd work || exit 1
	run repo-kickoff bash-cli greet
	assert_status 0
	# Move it away and hide repo-kickoff: it must not depend on either.
	mv greet "$TEST_TMP/moved"
	rm "$TEST_TMP/onpath/repo-kickoff"
	run "$TEST_TMP/moved/tests/smoke.sh"
	assert_status 0
	assert_not_contains "$(grep -r repo-kickoff "$TEST_TMP/moved" | grep -v 'Generated by repo-kickoff')" "repo-kickoff" \
		"the generated files only mention repo-kickoff as their origin"
}
